// Regenerate after adding or replacing a blog image. No native image library needed.
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {POSTS} from '../data/blog.js';

const require = createRequire(import.meta.url);
const imageSize = require('next/dist/compiled/image-size').default;
const sources = [...new Set(POSTS.flatMap(post => [
  post.hero, ...post.body.filter(block => block.type === 'img').map(block => block.src),
]))].sort();
const dimensions = Object.fromEntries(sources.map(src => {
  const {width, height} = imageSize(fs.readFileSync(`public${src}`));
  return [src, {width, height}];
}));
const output = '// Generated by node scripts/generate-blog-image-sizes.mjs.\n'
  + `export const BLOG_IMAGE_SIZES = ${JSON.stringify(dimensions, null, 2)};\n`;
const target = 'data/blog-image-sizes.js';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Blog image dimensions changed; regenerate the manifest.');
} else {
  fs.writeFileSync(target, output);
}
console.log(`Verified dimensions for ${sources.length} blog images.`);
